export function normalizeAnswer(value: string): string {
  return value
    .normalize("NFKC")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, " ")
    .trim()
    .replace(/\s+/g, " ");
}

export function isCorrectAnswer(question: Question, value: string): boolean {
  const submitted = normalizeAnswer(value);
  if (!submitted) return false;

  return [question.answer, ...(question.acceptedAnswers ?? [])].some(
    (answer) => normalizeAnswer(answer) === submitted,
  );
}

export function getRandomizedQuestions(count: number): Question[] {
  const shuffled = [...questionBank];

  for (let index = shuffled.length - 1; index > 0; index -= 1) {
    const swapIndex = Math.floor(Math.random() * (index + 1));
    [shuffled[index], shuffled[swapIndex]] = [shuffled[swapIndex], shuffled[index]];
  }

  return shuffled.slice(0, Math.min(count, shuffled.length));
}
